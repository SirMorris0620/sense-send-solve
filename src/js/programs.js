/* ============ COURSE PROGRAMS (one source for every board; used by the guided examples, the sandbox, and downloads) ============
   A program is a list of lines: [code, note] or {b:["s3",...], l:[[code, note], ...]} for board-only lines.
   {NAME} in code is replaced with the board's pin constant from PIN_PLAN. */
function pinK(board, name){ for (const k in PIN_PLAN){ const v = PIN_PLAN[k][board] && PIN_PLAN[k][board].k[name]; if (v != null) return v; } return "?"; }
function progLines(P, board){
  const out = []; P.forEach(x => { if (Array.isArray(x)) out.push(x); else if (x.b.includes(board)) x.l.forEach(y => out.push(y)); });
  return out.map(([c, n]) => [c.replace(/\{(\w+)\}/g, (m, k) => k === "ADC_MAX" ? BOARDS[board].adcMax + ".0" : k === "BOARD" ? BOARDS[board].short : k === "BOARDID" ? ({s3:"esp32s3", esp8266:"esp8266", uno:"unor4"})[board] : k === "VOLTS" ? (board === "uno" ? "5.0" : "3.3") : k === "VREF" ? (board === "uno" ? "5V" : "3V3") : pinK(board, k)), typeof n === "function" ? n(board) : (n || "").replace(/\{(\w+)\}/g, (m, k) => k === "ADC_MAX" ? String(BOARDS[board].adcMax) : k === "BOARD" ? BOARDS[board].short : k === "BITS" ? String(BOARDS[board].adcBits) : pinK(board, k))]);
}
const progSource = (P, board) => progLines(P, board).map(l => l[0]).join("\n") + "\n";
function progBlock(id, title){ const P = PROGRAMS[id]; return boardTabs(b => anat(`${title || P.title} <span class="mc-tag">${esc(BOARDS[b].short)}</span>`, progLines(P.lines, b), {file:P.file}), "Code for your board"); }

